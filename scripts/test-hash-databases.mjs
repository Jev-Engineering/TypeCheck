import assert from 'node:assert/strict';
import { randomBytes, randomUUID } from 'node:crypto';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { openPool, PostgresStore } from '../dist/server/postgres.js';
import { openMySqlPool, MySqlStore } from '../dist/server/mysql.js';
import { migrateDatabase } from '../dist/server/database.js';
import { normalize, ObjectStore } from '../dist/server/images.js';
import { Services } from '../dist/server/services.js';
import { JevClient } from '../dist/server/jev.js';
import { Vault } from '../dist/server/security.js';
import { baseRecord } from '../dist/shared/domain.js';
import { resolvePolicy } from '../dist/server/policy.js';
assert.equal(process.env.ALLOW_DATABASE_TESTS,'true');
const url=new URL(process.env.TEST_DATABASE_URL);
assert.ok(['127.0.0.1','localhost','[::1]'].includes(url.hostname));
assert.equal(url.pathname,'/guard_test');
const mysql=url.protocol==='mysql:';
assert.ok(mysql||url.protocol==='postgresql:');
const pool=await (mysql?openMySqlPool:openPool)(url.href),store=mysql?new MySqlStore(pool):new PostgresStore(pool);
const guild=String(Date.now())+'71', other=String(Date.now())+'72',dir=await mkdtemp(join(tmpdir(),'typecheck-hash-db-'));
try {
    await migrateDatabase(pool,mysql?'mysql':'postgres');
    await migrateDatabase(pool,mysql?'mysql':'postgres');
    const settings=(await store.getSettings(guild)).value;await store.getSettings(other);
    const image=await normalize(await readFile('fixtures/reference.png')),objects=new ObjectStore(dir);
    const ref={...baseRecord(guild,randomUUID()),name:'Synthetic',groupId:null,enabled:true,objectKey:await objects.put(guild,image),sha256:image.sha256,hashVersion:image.hashVersion,bytes:image.bytes.length,width:768,height:768,createdBy:guild};
    await store.put('images',ref,0);assert.deepEqual(await store.get('images',guild,ref.id),ref);assert.equal(await store.get('images',other,ref.id),null);
    const rule={...baseRecord(guild,randomUUID()),name:'Synthetic',type:'individual',referenceId:ref.id,groupId:null,mode:'exact',threshold:0.99,action:'ban',timeoutSeconds:600,deleteMessage:false,priority:0,enabled:true,automatic:true,secondVerification:true,reason:'Synthetic',approval:null};
    await store.put('rules',rule,0);
    const service=new Services(store,objects,new Vault(randomBytes(32).toString('base64')),new JevClient(async()=>{throw Error('provider forbidden');}),{});
    const result=await service.evaluate(guild,'synthetic',image,[rule],await store.all('images',guild),settings);
    assert.equal(result.hashComparisons,1);assert.equal(result.inputTokens,0);assert.equal(result.matches[0].probability,null);
    assert.equal(resolvePolicy([rule],result.matches,settings,[ref]).action,'review');
    const ev={...baseRecord(guild,randomUUID()),messageId:guild,channelId:guild,userId:guild,attachmentId:guild,matches:result.matches,outcome:'evaluated',error:null,inputTokens:0,model:null,hashComparisons:1,test:true};
    await store.put('evaluations',ev,0);assert.deepEqual(await store.get('evaluations',guild,ev.id),ev);assert.equal(await store.get('evaluations',other,ev.id),null);
    assert.equal((await store.usage(guild)).calls,0);assert.equal((await store.usage(guild)).inputTokens,0);
    const changed={...ref,revision:2,hashVersion:undefined};await store.put('images',changed,1);
    assert.equal(resolvePolicy([rule],result.matches,settings,[changed]),null);
    assert.equal((await store.get('images',guild,ref.id)).hashVersion,undefined);
    console.log(`${mysql?'MySQL':'PostgreSQL'}: repeat migrations, versioned/legacy reference and nullable evidence round trips, tenant isolation, hash-only zero quota/tokens, revision invalidation passed`);
} finally {
    const q=mysql?'?':'$1';
    await pool.query(`DELETE FROM moderation_rules WHERE guild_id=${q}`,[guild]);
    await pool.query(`DELETE FROM reference_images WHERE guild_id=${q}`,[guild]);
    for(const g of [guild,other])await pool.query(`DELETE FROM guilds WHERE id=${q}`,[g]);
    await pool.end();await rm(dir,{recursive:true,force:true});
}
